  await writeGeneratorFile(path.join(input.projectPath, '.gitignore'), GITIGNORE);
  await writeGeneratorFile(
    path.join(input.projectPath, 'README.md'),
    renderReadme(input.projectName)
  );
  await writeGeneratorFile(path.join(input.projectPath, 'src', 'redact.ts'), renderRedact());
  await writeGeneratorFile(path.join(input.projectPath, 'src', 'errors.ts'), renderErrors());
  await writeGeneratorFile(path.join(input.projectPath, 'src', 'port.ts'), renderPort());
